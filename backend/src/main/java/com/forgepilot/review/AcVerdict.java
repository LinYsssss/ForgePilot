package com.forgepilot.review;

/**
 * 一次 Review 对某条验收条件得出的结论（ARCHITECTURE.md 3.5）。
 *
 * <p>被审查修订的每一条 AC 最终都恰好落在其中一个取值上。模型漏答、
 * 无证据的已覆盖或零受审文件由校验器记为 UNKNOWN；尚未审查仍在读模型中用 null 表示。
 *
 * <p>分批过程从不产生这些取值。一个批次只看到 diff 的一部分，
 * 因此某个批次给出的裁定会与另一个批次矛盾；只有能看到所有批次证据的
 * 最终综合阶段才有资格下结论。
 */
public enum AcVerdict {

    /** diff 实现了这条验收条件，且证据就在变更文件之内。 */
    COVERED,

    /** 在被审查的那部分 diff 里未找到实现，不代表整个仓库没有实现。 */
    NOT_FOUND,

    /** 有东西涉及了它，但证据不完整或自相矛盾。 */
    AT_RISK,

    /** 信息不足，待人工核实；不是执行失败或尚未审查。 */
    UNKNOWN
}
